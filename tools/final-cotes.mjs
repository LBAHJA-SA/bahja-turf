const T = Array.from({length:5}, () => new Array(W).fill(0));
const C = Array.from({length:5}, () => []);
for (const rc of R) rc.forEach(([res, cote], i) => {
  const p = parseInt(res, 10);
  if (p >= 1 && p <= 5) { T[p-1][i]++; C[p-1].push(cote); }
});

const tot = T.map(r => r.reduce((a,b)=>a+b,0));
