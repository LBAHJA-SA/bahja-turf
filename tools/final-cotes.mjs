const missTop = [];
for (let i = 0; i < N; i++) {
  const have = new Set(R[i].filter(([r]) => /^[1-5]$/.test(r)).map(([r]) => parseInt(r, 10)));
  const gap = [1,2,3,4,5].filter(p => !have.has(p));
  if (gap.length) missTop.push({ i: i+1, gap });
}
console.log(`\n  سباقات فيهم المراكز 1-5 كاملين : ${N - missTop.length} من ${N}`);
if (missTop.length) {
  console.log('  ناقصين:');
  for (const m of missTop) console.log(`    سباق ${m.i}: المركز ${m.gap.join(', ')} ماكاينش`);
}

